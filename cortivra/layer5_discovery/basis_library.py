"""
Dimensionally constrained symbolic basis generator (`cortivra.layer5_discovery.basis_library`).

Constructs unit-consistent candidate basis functions across Port-Hamiltonian slots:
    - `"passive_dissipative"`: Non-negative diagonal dissipation operators `Delta_R_{ii}(x) >= 0`
      multiplying `-dH/dx_i`.
    - `"hamiltonian_potential"`: Scalar potential energy additions `Delta_H(x)` whose coupled
      vector field is `(J(x) - R(x)) * grad(Delta_H(x))`.
    - `"conservative_coupling"`: Skew-symmetric coupling terms `Delta_J_{ij}(x)` routing effort
      between state `i` and state `j`.
    - `"active_driven"`: Direct state-derivative expressions `Phi_i(x)` in `state_i.unit / time_unit`.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

import torch

from cortivra.layer1_axioms.hamiltonian import LawBrick, ParamSpec
from cortivra.layer1_axioms.units import DIMENSIONLESS, Unit
from cortivra.layer3_compiler.ast_nodes import (
    BinaryOpNode,
    ConstNode,
    ExprNode,
    PrimitiveCallNode,
    SymbolNode,
    UnaryOpNode,
    parse_symbolic_expr,
)
from cortivra.layer3_compiler.symbolic_compiler import build_symbol_table


@dataclass(frozen=True)
class CandidateBasisTerm:
    """
    Single dimensionally verified symbolic basis function and its evaluated flow column.

    Attributes:
        term_id: Short identifier for the basis term.
        expr_node: Symbolic `ExprNode` representing the unit-stripped basis shape `phi(x)`.
        param_spec: `ParamSpec` for the scalar coefficient multiplying `expr_node`.
        extra_param_specs: Additional nonlinear `ParamSpec`s embedded inside `expr_node` (e.g., `K_d`).
        thermodynamic_slot: One of `"passive_dissipative"`, `"hamiltonian_potential"`,
                            `"conservative_coupling"`, or `"active_driven"`.
        target_key: Integer state index `i`, pair `(i, j)`, or `"hamiltonian"` for scalar potentials.
        require_non_negative_coeff: True when coefficient must be `>= 0` to preserve the 2nd Law.
        complexity: AST structural complexity of `expr_node`.
        flow_column: `[T, StateDim]` vector field generated by unit coefficient `1.0 * expr_node`
                     along the observed state trajectory.
    """

    term_id: str
    expr_node: ExprNode
    param_spec: ParamSpec
    extra_param_specs: tuple[ParamSpec, ...]
    thermodynamic_slot: str
    target_key: int | tuple[int, int] | str
    require_non_negative_coeff: bool
    complexity: int
    flow_column: torch.Tensor


@dataclass(frozen=True)
class SymbolicBasisLibrary:
    """
    Collection of dimensionally verified `CandidateBasisTerm`s evaluated along a trajectory.

    Attributes:
        terms: Tuple of `CandidateBasisTerm` instances passing variance and collinearity filters.
        thermodynamic_slot: Primary thermodynamic slot of this library.
        characteristic_scales: Empirical half-saturation/scale estimates per state variable.
    """

    terms: tuple[CandidateBasisTerm, ...]
    thermodynamic_slot: str
    characteristic_scales: dict[str, float]


def estimate_characteristic_scales(
    brick: LawBrick,
    states: torch.Tensor,
    residual_flow: torch.Tensor | None = None,
) -> dict[str, float]:
    """
    Estimate empirical characteristic scales (such as half-maximum `K_d` or root-mean-square
    amplitude) for each state variable from the observed trajectory and residual flow.
    """
    x = states.detach().to(torch.float64)
    scales: dict[str, float] = {}
    for i, sp in enumerate(brick.state_specs):
        col = torch.abs(x[:, i])
        q50 = float(torch.quantile(col, 0.50).item()) if col.numel() > 1 else float(col.mean().item())
        rms = float(torch.sqrt(torch.mean(col * col) + 1e-18).item())
        scale_val = q50 if q50 > 1e-6 else max(rms, abs(sp.default_value), 1.0)

        # If residual flow is provided, refine scale toward the state value at 50% max residual
        if residual_flow is not None and residual_flow.shape[0] == x.shape[0]:
            r_mag = torch.linalg.norm(residual_flow.detach().to(torch.float64), dim=-1)
            r_max = float(torch.max(r_mag).item())
            r_min = float(torch.min(r_mag).item())
            if r_max - r_min > 1e-9:
                half_r = 0.5 * (r_max + r_min)
                closest_idx = int(torch.argmin(torch.abs(r_mag - half_r)).item())
                emp_half = float(col[closest_idx].item())
                if emp_half > 1e-6:
                    scale_val = emp_half
        scales[sp.name] = max(scale_val, 1e-4)
    return scales


def _build_state_env(
    brick: LawBrick,
    states: torch.Tensor,
    base_params: torch.Tensor,
    extra_params: Sequence[ParamSpec] = (),
) -> dict[str, torch.Tensor]:
    t_steps = states.shape[0]
    p_row = base_params[0] if base_params.ndim == 2 else base_params
    env: dict[str, torch.Tensor] = {}
    for i, sp in enumerate(brick.state_specs):
        env[sp.name] = states[:, i]
    for j, pp in enumerate(brick.param_specs):
        env[pp.name] = torch.full((t_steps,), float(p_row[j].item()), dtype=states.dtype, device=states.device)
    for ep in extra_params:
        env[ep.name] = torch.full((t_steps,), float(ep.default_value), dtype=states.dtype, device=states.device)
    return env


def _filter_collinear_terms(
    candidates: list[CandidateBasisTerm],
    min_norm: float = 1e-10,
    max_cosine_similarity: float = 0.9995,
) -> list[CandidateBasisTerm]:
    """
    Sort candidate basis terms by structural simplicity and prune zero-variance or
    nearly collinear terms (`|cos(theta)| > max_cosine_similarity`).
    """
    valid = [
        c for c in candidates
        if torch.isfinite(c.flow_column).all()
        and float(torch.linalg.norm(c.flow_column).item()) > min_norm
    ]
    # Prefer simpler AST expressions when two basis columns are nearly collinear
    valid.sort(key=lambda c: (c.complexity, len(c.extra_param_specs), c.term_id))

    kept: list[CandidateBasisTerm] = []
    kept_unit_vecs: list[torch.Tensor] = []

    for cand in valid:
        flat = cand.flow_column.reshape(-1).to(torch.float64)
        norm = float(torch.linalg.norm(flat).item())
        if norm <= min_norm:
            continue
        u_vec = flat / norm
        is_collinear = False
        for prev_u in kept_unit_vecs:
            cos_sim = float(torch.abs(torch.dot(u_vec, prev_u)).item())
            if cos_sim > max_cosine_similarity:
                is_collinear = True
                break
        if not is_collinear:
            kept.append(cand)
            kept_unit_vecs.append(u_vec)

    return kept


def generate_symbolic_basis_library(
    brick: LawBrick,
    states: torch.Tensor,
    base_params: torch.Tensor,
    thermodynamic_slot: str,
    affected_state_indices: Sequence[int] | None = None,
    residual_flow: torch.Tensor | None = None,
    max_polynomial_degree: int = 4,
    include_rational_primitives: bool = True,
    include_trigonometric: bool = True,
) -> SymbolicBasisLibrary:
    """
    Construct a dimensionally verified `SymbolicBasisLibrary` for `brick` in the specified
    `thermodynamic_slot` (`"passive_dissipative"`, `"hamiltonian_potential"`,
    `"conservative_coupling"`, or `"active_driven"`).

    Every generated candidate expression has its SI units inferred at construction time
    and its induced `[T, StateDim]` flow vector field evaluated along `states`.
    """
    if thermodynamic_slot not in (
        "passive_dissipative",
        "hamiltonian_potential",
        "conservative_coupling",
        "active_driven",
    ):
        raise ValueError(f"Unsupported thermodynamic_slot '{thermodynamic_slot}'.")

    x = states.detach().to(torch.float64)
    t_steps, state_dim = x.shape
    p_base = base_params.detach().to(torch.float64)
    if p_base.ndim == 1:
        p_base = p_base.unsqueeze(0)
    if p_base.shape[0] == 1 and t_steps > 1:
        p_batch = p_base.expand(t_steps, -1)
    else:
        p_batch = p_base

    scales = estimate_characteristic_scales(brick, x, residual_flow=residual_flow)
    target_indices = (
        list(affected_state_indices)
        if affected_state_indices
        else list(range(state_dim))
    )

    # Precompute base effort e(x) = dH/dx and base (J(x) - R(x)) along the trajectory
    effort_traj = brick.effort(x, p_batch).detach()  # [T, D]
    state_symbols = [SymbolNode(sp.name, sp.unit, role="state") for sp in brick.state_specs]

    candidates: list[CandidateBasisTerm] = []

    # Slot 1: Passive dissipative (Delta_R_{ii}(x) >= 0, flow_i = -Delta_R_{ii}(x) * e_i)
    if thermodynamic_slot == "passive_dissipative":
        for idx in target_indices:
            sp_target = brick.state_specs[idx]
            expected_r_unit = (sp_target.unit ** 2) / (brick.energy_unit * brick.time_unit)
            e_col = effort_traj[:, idx]
            if float(torch.linalg.norm(e_col).item()) <= 1e-12:
                continue

            # Non-negative polynomial basis terms: 1, x_j^2, x_j^4, x_j^2 * x_k^2
            non_neg_shapes: list[tuple[str, ExprNode, tuple[ParamSpec, ...]]] = [
                ("const", ConstNode(1.0, DIMENSIONLESS), ()),
            ]
            for j, sym_j in enumerate(state_symbols):
                non_neg_shapes.append(
                    (f"{sym_j.name}_sq", BinaryOpNode("**", sym_j, ConstNode(2.0, DIMENSIONLESS)), ())
                )
                if max_polynomial_degree >= 4:
                    non_neg_shapes.append(
                        (f"{sym_j.name}_pow4", BinaryOpNode("**", sym_j, ConstNode(4.0, DIMENSIONLESS)), ())
                    )
                for k in range(j + 1, state_dim):
                    sym_k = state_symbols[k]
                    prod_sq = BinaryOpNode(
                        "*",
                        BinaryOpNode("**", sym_j, ConstNode(2.0, DIMENSIONLESS)),
                        BinaryOpNode("**", sym_k, ConstNode(2.0, DIMENSIONLESS)),
                    )
                    non_neg_shapes.append((f"{sym_j.name}2_{sym_k.name}2", prod_sq, ()))
                    if sym_j.unit == sym_k.unit:
                        diff_jk = BinaryOpNode("-", sym_j, sym_k)
                        non_neg_shapes.append(
                            (
                                f"diff_{sym_j.name}_{sym_k.name}_sq",
                                BinaryOpNode("**", diff_jk, ConstNode(2.0, DIMENSIONLESS)),
                                (),
                            )
                        )

            if include_rational_primitives:
                for j, sym_j in enumerate(state_symbols):
                    kd_val = scales[sym_j.name]
                    kd_spec = ParamSpec(
                        name=f"kd_diss_{idx}_{sym_j.name}",
                        unit=sym_j.unit,
                        default_value=kd_val,
                        min_value=max(kd_val * 0.05, 1e-5),
                        max_value=max(kd_val * 20.0, 10.0),
                    )
                    kd_sym = SymbolNode(kd_spec.name, kd_spec.unit, role="param")
                    hill1 = PrimitiveCallNode("hill", ( UnaryOpNode("abs", sym_j), kd_sym, ConstNode(1.0, DIMENSIONLESS) ))
                    hill2 = PrimitiveCallNode("hill", ( UnaryOpNode("abs", sym_j), kd_sym, ConstNode(2.0, DIMENSIONLESS) ))
                    non_neg_shapes.append((f"hill1_{sym_j.name}", hill1, (kd_spec,)))
                    non_neg_shapes.append((f"hill2_{sym_j.name}", hill2, (kd_spec,)))

            for shape_tag, shape_node, extra_specs in non_neg_shapes:
                shape_u = shape_node.infer_unit()
                coeff_unit = expected_r_unit / shape_u
                p_name = f"g_diss_{idx}_{shape_tag}"
                p_spec = ParamSpec(
                    name=p_name,
                    unit=coeff_unit,
                    default_value=0.1,
                    min_value=0.0,
                    max_value=1e6,
                )
                p_sym = SymbolNode(p_name, coeff_unit, role="param")
                full_node = (
                    p_sym
                    if (isinstance(shape_node, ConstNode) and shape_node.value == 1.0)
                    else BinaryOpNode("*", p_sym, shape_node)
                )
                env = _build_state_env(brick, x, p_base, extra_specs)
                shape_vals = shape_node.eval_tensor(env)
                flow_col = torch.zeros((t_steps, state_dim), dtype=torch.float64, device=x.device)
                flow_col[:, idx] = -shape_vals * e_col

                candidates.append(
                    CandidateBasisTerm(
                        term_id=f"diss_{idx}_{shape_tag}",
                        expr_node=full_node,
                        param_spec=p_spec,
                        extra_param_specs=extra_specs,
                        thermodynamic_slot="passive_dissipative",
                        target_key=idx,
                        require_non_negative_coeff=True,
                        complexity=shape_node.tree_complexity(),
                        flow_column=flow_col,
                    )
                )

    # Slot 2: Hamiltonian potential (Delta_H(x), flow = (J - R) * grad(Delta_H))
    elif thermodynamic_slot == "hamiltonian_potential" and not brick.is_matrix_free:
        j_traj = brick.structure_matrix(x, p_batch).detach()
        r_traj = brick.dissipation_matrix(x, p_batch).detach()
        jr_traj = j_traj - r_traj  # [T, D, D]

        potential_shapes: list[tuple[str, ExprNode, tuple[ParamSpec, ...]]] = []
        for i, sym_i in enumerate(state_symbols):
            for deg in range(1, max_polynomial_degree + 1):
                node = (
                    sym_i
                    if deg == 1
                    else BinaryOpNode(
                        "*",
                        ConstNode(1.0 / float(deg), DIMENSIONLESS),
                        BinaryOpNode("**", sym_i, ConstNode(float(deg), DIMENSIONLESS)),
                    )
                )
                potential_shapes.append((f"H_{sym_i.name}_p{deg}", node, ()))

            if include_trigonometric and sym_i.unit.dimension.is_dimensionless:
                potential_shapes.append((f"H_cos_{sym_i.name}", UnaryOpNode("cos", sym_i), ()))
                potential_shapes.append((f"H_sin_{sym_i.name}", UnaryOpNode("sin", sym_i), ()))

            for j in range(i + 1, state_dim):
                sym_j = state_symbols[j]
                potential_shapes.append((f"H_{sym_i.name}_{sym_j.name}", BinaryOpNode("*", sym_i, sym_j), ()))
                if max_polynomial_degree >= 3:
                    potential_shapes.append(
                        (
                            f"H_{sym_i.name}2_{sym_j.name}",
                            BinaryOpNode("*", BinaryOpNode("**", sym_i, ConstNode(2.0, DIMENSIONLESS)), sym_j),
                            (),
                        )
                    )
                    potential_shapes.append(
                        (
                            f"H_{sym_i.name}_{sym_j.name}2",
                            BinaryOpNode("*", sym_i, BinaryOpNode("**", sym_j, ConstNode(2.0, DIMENSIONLESS))),
                            (),
                        )
                    )
                if max_polynomial_degree >= 4:
                    potential_shapes.append(
                        (
                            f"H_{sym_i.name}2_{sym_j.name}2",
                            BinaryOpNode(
                                "*",
                                BinaryOpNode("**", sym_i, ConstNode(2.0, DIMENSIONLESS)),
                                BinaryOpNode("**", sym_j, ConstNode(2.0, DIMENSIONLESS)),
                            ),
                            (),
                        )
                    )
                if sym_i.unit == sym_j.unit:
                    diff_ij = BinaryOpNode("-", sym_i, sym_j)
                    potential_shapes.append(
                        (
                            f"H_diff_{sym_i.name}_{sym_j.name}_p2",
                            BinaryOpNode(
                                "*",
                                ConstNode(0.5, DIMENSIONLESS),
                                BinaryOpNode("**", diff_ij, ConstNode(2.0, DIMENSIONLESS)),
                            ),
                            (),
                        )
                    )
                    if max_polynomial_degree >= 4:
                        potential_shapes.append(
                            (
                                f"H_diff_{sym_i.name}_{sym_j.name}_p4",
                                BinaryOpNode(
                                    "*",
                                    ConstNode(0.25, DIMENSIONLESS),
                                    BinaryOpNode("**", diff_ij, ConstNode(4.0, DIMENSIONLESS)),
                                ),
                                (),
                            )
                        )
                    if include_trigonometric and sym_i.unit.dimension.is_dimensionless:
                        potential_shapes.append(
                            (f"H_cos_diff_{sym_i.name}_{sym_j.name}", UnaryOpNode("cos", diff_ij), ())
                        )
                    # Regularized inverse-distance potential 1 / sqrt((x_i - x_j)^2 + eps^2)
                    eps_sq = max((0.05 * min(scales[sym_i.name], scales[sym_j.name])) ** 2, 1e-4)
                    r2_node = BinaryOpNode(
                        "+",
                        BinaryOpNode("**", diff_ij, ConstNode(2.0, DIMENSIONLESS)),
                        ConstNode(eps_sq, sym_i.unit ** 2),
                    )
                    inv_r_node = BinaryOpNode("/", ConstNode(1.0, DIMENSIONLESS), UnaryOpNode("sqrt", r2_node))
                    potential_shapes.append((f"H_inv_dist_{sym_i.name}_{sym_j.name}", inv_r_node, ()))

        for shape_tag, shape_node, extra_specs in potential_shapes:
            shape_u = shape_node.infer_unit()
            coeff_unit = brick.energy_unit / shape_u
            p_name = f"k_{shape_tag}"
            p_spec = ParamSpec(
                name=p_name,
                unit=coeff_unit,
                default_value=0.1,
                min_value=-1e6,
                max_value=1e6,
            )
            p_sym = SymbolNode(p_name, coeff_unit, role="param")
            full_h_node = BinaryOpNode("*", p_sym, shape_node)

            # Compute exact symbolic gradient grad_x(shape_node)
            env = _build_state_env(brick, x, p_base, extra_specs)
            grad_cols = [
                shape_node.diff(sp.name).simplify().eval_tensor(env)
                for sp in brick.state_specs
            ]
            grad_mat = torch.stack(grad_cols, dim=-1)  # [T, D]
            flow_col = torch.bmm(jr_traj, grad_mat.unsqueeze(-1)).squeeze(-1)  # [T, D]

            candidates.append(
                CandidateBasisTerm(
                    term_id=shape_tag,
                    expr_node=full_h_node,
                    param_spec=p_spec,
                    extra_param_specs=extra_specs,
                    thermodynamic_slot="hamiltonian_potential",
                    target_key="hamiltonian",
                    require_non_negative_coeff=False,
                    complexity=shape_node.tree_complexity(),
                    flow_column=flow_col,
                )
            )

    # Slot 3: Conservative coupling (Delta_J_{ij}(x), flow_i += J_ij e_j, flow_j -= J_ij e_i)
    elif thermodynamic_slot == "conservative_coupling" and state_dim >= 2:
        for i in range(state_dim):
            for j in range(i + 1, state_dim):
                sp_i, sp_j = brick.state_specs[i], brick.state_specs[j]
                expected_j_unit = (sp_i.unit * sp_j.unit) / (brick.energy_unit * brick.time_unit)
                e_i, e_j = effort_traj[:, i], effort_traj[:, j]

                j_shapes: list[tuple[str, ExprNode]] = [
                    ("const", ConstNode(1.0, DIMENSIONLESS)),
                ]
                for k, sym_k in enumerate(state_symbols):
                    j_shapes.append((f"{sym_k.name}", sym_k))
                    j_shapes.append((f"{sym_k.name}_sq", BinaryOpNode("**", sym_k, ConstNode(2.0, DIMENSIONLESS))))

                for shape_tag, shape_node in j_shapes:
                    shape_u = shape_node.infer_unit()
                    coeff_unit = expected_j_unit / shape_u
                    p_name = f"j_cpl_{i}_{j}_{shape_tag}"
                    p_spec = ParamSpec(
                        name=p_name,
                        unit=coeff_unit,
                        default_value=0.1,
                        min_value=-1e6,
                        max_value=1e6,
                    )
                    p_sym = SymbolNode(p_name, coeff_unit, role="param")
                    full_node = (
                        p_sym
                        if (isinstance(shape_node, ConstNode) and shape_node.value == 1.0)
                        else BinaryOpNode("*", p_sym, shape_node)
                    )
                    env = _build_state_env(brick, x, p_base)
                    vals = shape_node.eval_tensor(env)
                    flow_col = torch.zeros((t_steps, state_dim), dtype=torch.float64, device=x.device)
                    flow_col[:, i] = vals * e_j
                    flow_col[:, j] = -vals * e_i

                    candidates.append(
                        CandidateBasisTerm(
                            term_id=f"jcpl_{i}_{j}_{shape_tag}",
                            expr_node=full_node,
                            param_spec=p_spec,
                            extra_param_specs=(),
                            thermodynamic_slot="conservative_coupling",
                            target_key=(i, j),
                            require_non_negative_coeff=False,
                            complexity=shape_node.tree_complexity(),
                            flow_column=flow_col,
                        )
                    )

    # Slot 4: Active driven / general vector field (Phi_i(x) in state_i.unit / time_unit)
    else:
        for idx in target_indices:
            sp_target = brick.state_specs[idx]
            target_flow_unit = sp_target.unit / brick.time_unit

            drive_shapes: list[tuple[str, ExprNode, tuple[ParamSpec, ...]]] = [
                ("bias", ConstNode(1.0, DIMENSIONLESS), ()),
            ]
            for j, sym_j in enumerate(state_symbols):
                for deg in range(1, min(max_polynomial_degree, 3) + 1):
                    node = (
                        sym_j
                        if deg == 1
                        else BinaryOpNode("**", sym_j, ConstNode(float(deg), DIMENSIONLESS))
                    )
                    drive_shapes.append((f"{sym_j.name}_p{deg}", node, ()))

                if include_trigonometric and sym_j.unit.dimension.is_dimensionless:
                    drive_shapes.append((f"sin_{sym_j.name}", UnaryOpNode("sin", sym_j), ()))
                    drive_shapes.append((f"cos_{sym_j.name}", UnaryOpNode("cos", sym_j), ()))

                for k in range(j + 1, state_dim):
                    sym_k = state_symbols[k]
                    drive_shapes.append(
                        (f"{sym_j.name}_{sym_k.name}", BinaryOpNode("*", sym_j, sym_k), ())
                    )
                    if max_polynomial_degree >= 3:
                        drive_shapes.append(
                            (
                                f"{sym_j.name}2_{sym_k.name}",
                                BinaryOpNode("*", BinaryOpNode("**", sym_j, ConstNode(2.0, DIMENSIONLESS)), sym_k),
                                (),
                            )
                        )
                        drive_shapes.append(
                            (
                                f"{sym_j.name}_{sym_k.name}2",
                                BinaryOpNode("*", sym_j, BinaryOpNode("**", sym_k, ConstNode(2.0, DIMENSIONLESS))),
                                (),
                            )
                        )
                    if sym_j.unit == sym_k.unit:
                        diff_jk = BinaryOpNode("-", sym_j, sym_k)
                        if max_polynomial_degree >= 3:
                            drive_shapes.append(
                                (
                                    f"diff_{sym_j.name}_{sym_k.name}_p3",
                                    BinaryOpNode("**", diff_jk, ConstNode(3.0, DIMENSIONLESS)),
                                    (),
                                )
                            )
                        if include_trigonometric and sym_j.unit.dimension.is_dimensionless:
                            drive_shapes.append(
                                (f"sin_diff_{sym_j.name}_{sym_k.name}", UnaryOpNode("sin", diff_jk), ())
                            )

                if include_rational_primitives:
                    kd_val = scales[sym_j.name]
                    for n_exp in (1, 2, 3, 4):
                        kd_spec = ParamSpec(
                            name=f"kd_act_{idx}_{sym_j.name}_n{n_exp}",
                            unit=sym_j.unit,
                            default_value=kd_val,
                            min_value=max(kd_val * 0.05, 1e-5),
                            max_value=max(kd_val * 20.0, 10.0),
                        )
                        kd_sym = SymbolNode(kd_spec.name, kd_spec.unit, role="param")
                        hill_node = PrimitiveCallNode(
                            "hill",
                            (sym_j, kd_sym, ConstNode(float(n_exp), DIMENSIONLESS)),
                        )
                        drive_shapes.append((f"hill{n_exp}_{sym_j.name}", hill_node, (kd_spec,)))

                        hill_inh = PrimitiveCallNode(
                            "hill_inhib",
                            (sym_j, kd_sym, ConstNode(float(n_exp), DIMENSIONLESS)),
                        )
                        drive_shapes.append((f"hill_inh{n_exp}_{sym_j.name}", hill_inh, (kd_spec,)))

                    # Boltzmann sigmoidal barrier switch boltzmann(x_j, x_half, k_slope)
                    x_col_j = x[:, j]
                    xh_val = float(torch.mean(x_col_j).item())
                    k_slope_val = max(float(torch.std(x_col_j).item()) * 0.5, 0.1)
                    xh_spec = ParamSpec(
                        name=f"xh_boltz_{idx}_{sym_j.name}",
                        unit=sym_j.unit,
                        default_value=xh_val,
                        min_value=xh_val - 10.0 * k_slope_val - 10.0,
                        max_value=xh_val + 10.0 * k_slope_val + 10.0,
                    )
                    ks_spec = ParamSpec(
                        name=f"ks_boltz_{idx}_{sym_j.name}",
                        unit=sym_j.unit,
                        default_value=k_slope_val,
                        min_value=max(k_slope_val * 0.05, 1e-4),
                        max_value=max(k_slope_val * 20.0, 20.0),
                    )
                    boltz_node = PrimitiveCallNode(
                        "boltzmann",
                        (
                            sym_j,
                            SymbolNode(xh_spec.name, sym_j.unit, role="param"),
                            SymbolNode(ks_spec.name, sym_j.unit, role="param"),
                        ),
                    )
                    drive_shapes.append((f"boltz_{sym_j.name}", boltz_node, (xh_spec, ks_spec)))

            for shape_tag, shape_node, extra_specs in drive_shapes:
                shape_u = shape_node.infer_unit()
                coeff_unit = target_flow_unit / shape_u
                p_name = f"c_drv_{idx}_{shape_tag}"
                p_spec = ParamSpec(
                    name=p_name,
                    unit=coeff_unit,
                    default_value=0.1,
                    min_value=-1e6,
                    max_value=1e6,
                )
                p_sym = SymbolNode(p_name, coeff_unit, role="param")
                full_node = (
                    p_sym
                    if (isinstance(shape_node, ConstNode) and shape_node.value == 1.0)
                    else BinaryOpNode("*", p_sym, shape_node)
                )
                env = _build_state_env(brick, x, p_base, extra_specs)
                vals = shape_node.eval_tensor(env)
                flow_col = torch.zeros((t_steps, state_dim), dtype=torch.float64, device=x.device)
                flow_col[:, idx] = vals

                candidates.append(
                    CandidateBasisTerm(
                        term_id=f"drv_{idx}_{shape_tag}",
                        expr_node=full_node,
                        param_spec=p_spec,
                        extra_param_specs=extra_specs,
                        thermodynamic_slot="active_driven",
                        target_key=idx,
                        require_non_negative_coeff=False,
                        complexity=shape_node.tree_complexity(),
                        flow_column=flow_col,
                    )
                )

    filtered = _filter_collinear_terms(candidates)
    return SymbolicBasisLibrary(
        terms=tuple(filtered),
        thermodynamic_slot=thermodynamic_slot,
        characteristic_scales=scales,
    )
