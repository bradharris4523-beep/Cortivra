def test_no_false_discovery_when_parameters_explain_trajectory() -> None:
    """
    Verify that when an observed trajectory is generated by shifted parameters of the
    known baseline model (`k = 3.2` instead of `1.0`), `discover_and_compile_law`
    calibrates `k = 3.2` and sets `discovery_triggered == False` without inventing
    spurious symbolic terms.
    """
    base = CanonicalHamiltonianBrick(k_default=1.0, m_default=1.0, damping_default=0.15)
    true_params = torch.tensor([[3.2, 1.0, 0.15]], dtype=torch.float64)
    x0 = torch.tensor([[1.4, -0.6]], dtype=torch.float64)
    dt = 0.03

    gt_roll = rollout_trajectories(base, x0, true_params, dt=dt, num_steps=35, integrator="rk4")
    rep = discover_and_compile_law(
        base_brick=base,
        observed_states=gt_roll.states[0],
        dt=dt,
        observed_dx_dt=gt_roll.flows[0],
        noise_floor_std=1e-2,
    )
    assert not rep.discovery_triggered
    assert rep.winning_brick is base
    assert abs(float(rep.winning_params[0, 0].item()) - 3.2) < 1e-2
    assert rep.audit_certificate.passed_all


def test_passive_dissipative_cubic_damping_operator_discovery() -> None:
    """
    Verify that `discover_and_compile_law` discovers an unmodeled nonlinear dissipative
    operator `Delta_R_{11}(q, p) = gamma_c * p^2 >= 0` directly in the `"passive_dissipative"`
    Port-Hamiltonian slot, preserving the 2nd Law of Thermodynamics everywhere.
    """
    base = CanonicalHamiltonianBrick(k_default=1.5, m_default=1.0, damping_default=0.05)
    true_patched = compile_residual_patch_brick(
        name="true_cubic_damped",
        base_brick=base,
        patch_param_specs=[ParamSpec("gamma_c", base.state_specs[1].unit, default_value=0.65, min_value=0.0)],
        thermodynamic_mode="passive_dissipative",
        patch_expressions={1: "gamma_c * p^2"},
    )
    true_params = torch.tensor([[1.5, 1.0, 0.05, 0.65]], dtype=torch.float64)
    x0 = torch.tensor([[1.6, 1.1]], dtype=torch.float64)
    dt = 0.03

    gt_roll = rollout_trajectories(true_patched, x0, true_params, dt=dt, num_steps=40, integrator="rk4")
    cal_rep = calibrate_and_audit_residual(
        brick=base,
        observed_states=gt_roll.states[0],
        dt=dt,
        observed_dx_dt=gt_roll.flows[0],
        noise_floor_std=1e-3,
        custom_bounds={"k": (1.5, 1.5), "m": (1.0, 1.0), "damping": (0.05, 0.05)},
    )
    assert cal_rep.latent_mechanism_required
    assert cal_rep.residual_analysis.thermodynamic_class == "passive_dissipative"

    disc_rep = discover_and_compile_law(
        base_brick=base,
        observed_states=gt_roll.states[0],
        dt=dt,
        observed_dx_dt=gt_roll.flows[0],
        calibration_report=cal_rep,
        max_active_terms=2,
    )
    assert disc_rep.discovery_triggered
    assert disc_rep.winning_candidate is not None
    assert disc_rep.winning_candidate.thermodynamic_slot == "passive_dissipative"
    assert isinstance(disc_rep.winning_brick, ResidualPatchedLawBrick)
    assert disc_rep.audit_certificate.passed_all
    assert disc_rep.portfolio_rankings[0].funnel_report.vector_field_r2 > 0.999
    assert disc_rep.portfolio_rankings[0].funnel_report.trajectory_r2 > 0.995
    assert disc_rep.archetype.archetype_name == "nonlinear_state_dependent_dissipation"
    assert disc_rep.archetype.parity_symmetry == "even"
    assert abs(float(disc_rep.winning_params[0, -1].item()) - 0.65) < 1e-2


def test_conservative_hamiltonian_quartic_duffing_potential_discovery() -> None:
    """
    Verify that when an undamped oscillator has an unmodeled conservative anharmonic
    potential `Delta_H(q) = 0.25 * alpha * q^4` (producing restoring force `-alpha * q^3`
    on `dp/dt`), Layer 5 classifies the residual as `"reactive_storage"` and discovers the
    scalar Hamiltonian addition `Delta_H(q)` inside `HamiltonianPatchedLawBrick`,
    conserving total energy `H_base + Delta_H` with zero external power.
    """
    base = CanonicalHamiltonianBrick(k_default=1.2, m_default=1.0, damping_default=0.0)
    alpha_true = 0.8
    true_duffing = HamiltonianPatchedLawBrick(
        name="true_duffing_oscillator",
        base_brick=base,
        patch_param_specs=[
            ParamSpec(
                "alpha_q4",
                base.energy_unit / (base.state_specs[0].unit ** 4),
                default_value=alpha_true,
            )
        ],
        delta_hamiltonian_expr="0.25 * alpha_q4 * q^4",
    )
    p_true = torch.tensor([[1.2, 1.0, 0.0, alpha_true]], dtype=torch.float64)
    x0 = torch.tensor([[1.5, 0.5]], dtype=torch.float64)
    dt = 0.025

    gt_roll = rollout_trajectories(
        true_duffing, x0, p_true, dt=dt, num_steps=45, integrator="symplectic_midpoint"
    )
    assert gt_roll.max_energy_drift < 1e-3

    cal_rep = calibrate_and_audit_residual(
        brick=base,
        observed_states=gt_roll.states[0],
        dt=dt,
        observed_dx_dt=gt_roll.flows[0],
        noise_floor_std=1e-3,
        custom_bounds={"k": (1.2, 1.2), "m": (1.0, 1.0), "damping": (0.0, 0.0)},
    )
    assert cal_rep.latent_mechanism_required
    assert cal_rep.residual_analysis.thermodynamic_class in ("reactive_storage", "active_driven")

    disc_rep = discover_and_compile_law(
        base_brick=base,
        observed_states=gt_roll.states[0],
        dt=dt,
        observed_dx_dt=gt_roll.flows[0],
        calibration_report=cal_rep,
        max_active_terms=1,
    )
    assert disc_rep.discovery_triggered
    assert isinstance(disc_rep.winning_brick, HamiltonianPatchedLawBrick)
    assert disc_rep.audit_certificate.passed_all
    assert disc_rep.archetype.archetype_name == "conservative_anharmonic_potential"
    assert abs(float(disc_rep.winning_params[0, -1].item()) - alpha_true) < 1e-2

    # Roll out the discovered HamiltonianPatchedLawBrick with symplectic_midpoint and verify energy conservation
    disc_roll = rollout_trajectories(
        disc_rep.winning_brick,
        x0,
        disc_rep.winning_params,
        dt=dt,
        num_steps=45,
        integrator="symplectic_midpoint",
    )
    assert disc_roll.max_energy_drift < 1e-3
    assert torch.allclose(disc_roll.states, gt_roll.states, atol=1e-2)


def test_sanathanan_koerner_rational_pade_receptor_saturation_discovery() -> None:
    """
    Verify that `discover_rational_pade_candidates` and `discover_and_compile_law`
    recover a saturating cooperative Hill / Michaelis-Menten pharmacological response
    `Phi(L) = V_max * L^2 / (K_d^2 + L^2)` (both amplitude `V_max` and half-saturation `K_d`),
    and remain bounded when extrapolated to 10x concentration.
    """
    spec = SymbolicSystemSpec(
        name="receptor_signaling_baseline",
        domain="chemistry",
        state_specs=[
            StateVarSpec("L", DIMENSIONLESS, default_value=1.0, homeostatic_min=0.0, homeostatic_max=100.0, hard_min=0.0, hard_max=500.0),
        ],
        param_specs=[
            ParamSpec("k_clear", DIMENSIONLESS / s, default_value=0.2, min_value=0.0, max_value=5.0),
        ],
        time_unit=s,
        energy_unit=DIMENSIONLESS,
        hamiltonian_expr="0.5 * L^2",
        dissipation_diag_exprs=["k_clear"],
    )
    base_receptor = compile_symbolic_system(spec)
    p_base = torch.tensor([[0.2]], dtype=torch.float64)

    # Evaluate across a sweep of ligand concentrations L in [0.1, 8.0] mM
    l_vals = torch.linspace(0.1, 8.0, 45, dtype=torch.float64).unsqueeze(-1)  # [45, 1]
    vmax_true = 4.5
    kd_true = 1.8
    hill_residual = vmax_true * (l_vals ** 2) / (kd_true ** 2 + l_vals ** 2)
    obs_dx = base_receptor.flow(l_vals, p_base.expand(45, -1)) + hill_residual

    pade_cands = discover_rational_pade_candidates(
        brick=base_receptor,
        states=l_vals,
        target_residual=hill_residual,
        affected_state_indices=[0],
    )
    assert len(pade_cands) >= 1
    best_pade = min(pade_cands, key=lambda c: c.bic_score)
    assert best_pade.vector_field_r2 > 0.999
    # Verify Sanathanan-Koerner directly recovered V_max ~ 4.5 and K_d ~ 1.8
    fitted_defaults = {ps.name: ps.default_value for ps in best_pade.param_specs}
    vmax_est = next(v for k, v in fitted_defaults.items() if "vmax" in k)
    kd_est = next(v for k, v in fitted_defaults.items() if "kd" in k)
    assert abs(vmax_est - vmax_true) < 0.05
    assert abs(kd_est - kd_true) < 0.05

    cal_rep = calibrate_and_audit_residual(
        brick=base_receptor,
        observed_states=l_vals,
        dt=0.05,
        observed_dx_dt=obs_dx,
        noise_floor_std=1e-3,
        custom_bounds={"k_clear": (0.2, 0.2)},
    )
    disc_rep = discover_and_compile_law(
        base_brick=base_receptor,
        observed_states=l_vals,
        dt=0.05,
        observed_dx_dt=obs_dx,
        calibration_report=cal_rep,
    )
    assert disc_rep.discovery_triggered
    assert disc_rep.archetype.archetype_name == "cooperative_hill_michaelis_saturation"
    assert disc_rep.archetype.is_saturating

    # Verify boundedness at 10x concentration extrapolation (L = 80 mM): active patch flow <= V_max
    assert isinstance(disc_rep.winning_brick, ResidualPatchedLawBrick)
    x_extrap = torch.tensor([[80.0]], dtype=torch.float64)
    patch_flow_extrap = float(
        disc_rep.winning_brick.compute_active_patch_flow(x_extrap, disc_rep.winning_params)[0, 0].item()
    )
    assert abs(patch_flow_extrap - vmax_true) < 0.1


def test_weak_integral_collocation_noise_resilience() -> None:
    """
    Verify that weak-integral collocation in `solve_sparse_pareto_front` accurately
    identifies the true sparse symbolic law even when pointwise derivative estimates
    are corrupted by zero-mean high-frequency measurement noise.
    """
    base = CanonicalHamiltonianBrick(k_default=1.0, m_default=1.0, damping_default=0.1)
    p_base = base.default_params(batch_size=1, dtype=torch.float64)
    x0 = torch.tensor([[1.5, 0.8]], dtype=torch.float64)
    dt = 0.02

    roll = rollout_trajectories(base, x0, p_base, dt=dt, num_steps=60, integrator="rk4")
    states = roll.states[0]  # [61, 2]
    p_col = states[:, 1]
    e_p = base.effort(states, p_base.expand(61, -1))[:, 1]

    # True missing dissipative law: Delta_R_{11} = 0.5 * p^2 -> residual_1 = -0.5 * p^2 * e_p
    clean_res = torch.zeros_like(states)
    clean_res[:, 1] = -0.5 * (p_col ** 2) * e_p

    # Add deterministic high-frequency alternating derivative noise (+- 0.08)
    t_idx = torch.arange(61, dtype=torch.float64)
    hf_noise = 0.08 * torch.sin(15.0 * t_idx)
    noisy_res = clean_res.clone()
    noisy_res[:, 1] = noisy_res[:, 1] + hf_noise

    lib = generate_symbolic_basis_library(
        brick=base,
        states=states,
        base_params=p_base,
        thermodynamic_slot="passive_dissipative",
        affected_state_indices=[1],
        residual_flow=noisy_res,
        include_rational_primitives=False,
    )
    pareto_rep = solve_sparse_pareto_front(
        library=lib,
        target_residual=noisy_res,
        dt=dt,
        max_active_terms=1,
        window_steps=6,
        integral_weight=1.0,
    )
    assert "diss_1_p_sq" in pareto_rep.best_candidate.active_term_ids
    fitted_coeff = pareto_rep.best_candidate.param_specs[0].default_value
    assert abs(fitted_coeff - 0.5) < 0.04


def test_non_markovian_hysteresis_detection_and_latent_state_augmentation() -> None:
    """
    Verify that when an observed state `V(t)` is coupled to an UNMEASURED internal adaptation
    state `z(t)` (causing a hysteresis loop where identical `V` values map to different residuals
    at different times), Layer 5:
        1. Detects `memory_report.is_non_markovian == True`.
        2. Synthesizes a 2-state `LatentAugmentedLawBrick` with new state variable `z_latent`.
        3. Calibrates the 2-state brick against the 1D observed trajectory `V(t)` (`R^2 > 0.96`)
           and passes `audit_law_brick`.
    """
    # Ground-truth 2-state system: V (observed) and z_adapt (hidden)
    true_spec = SymbolicSystemSpec(
        name="true_2state_sensory_adaptation",
        domain="electrodynamics",
        state_specs=[
            StateVarSpec("V", DIMENSIONLESS, default_value=1.2, homeostatic_min=-50.0, homeostatic_max=50.0),
            StateVarSpec("z_adapt", DIMENSIONLESS, default_value=0.0, homeostatic_min=-50.0, homeostatic_max=50.0),
        ],
        param_specs=[
            ParamSpec("g_leak", DIMENSIONLESS / ms, default_value=0.1, min_value=0.0, max_value=5.0),
            ParamSpec("k_decay", DIMENSIONLESS / ms, default_value=0.4, min_value=0.0, max_value=5.0),
            ParamSpec("k_couple", DIMENSIONLESS / ms, default_value=-1.5, min_value=-10.0, max_value=10.0),
            ParamSpec("c_drive", DIMENSIONLESS / ms, default_value=1.2, min_value=-10.0, max_value=10.0),
        ],
        time_unit=ms,
        energy_unit=DIMENSIONLESS,
        hamiltonian_expr="0.5 * V^2",
        dissipation_diag_exprs=["g_leak", "0.0"],
        external_drive_exprs=["k_couple * z_adapt", "-k_decay * z_adapt + c_drive * V"],
    )
    true_2state = compile_symbolic_system(true_spec)
    x0_2d = torch.tensor([[1.5, 0.0]], dtype=torch.float64)
    p_2d = true_2state.default_params(batch_size=1, dtype=torch.float64)
    dt = 0.08

    gt_roll = rollout_trajectories(true_2state, x0_2d, p_2d, dt=dt, num_steps=45, integrator="rk4")
    obs_v_only = gt_roll.states[0, :, :1]      # [46, 1] — ONLY V(t) is observed; z_adapt(t) is hidden!
    obs_dv_only = gt_roll.flows[0, :, :1]      # [46, 1]

    # 1D baseline model that only knows about V and g_leak (unaware of z_adapt)
    base_1d_spec = SymbolicSystemSpec(
        name="baseline_1state_membrane",
        domain="electrodynamics",
        state_specs=[
            StateVarSpec("V", DIMENSIONLESS, default_value=1.2, homeostatic_min=-50.0, homeostatic_max=50.0),
        ],
        param_specs=[
            ParamSpec("g_leak", DIMENSIONLESS / ms, default_value=0.1, min_value=0.0, max_value=5.0),
        ],
        time_unit=ms,
        energy_unit=DIMENSIONLESS,
        hamiltonian_expr="0.5 * V^2",
        dissipation_diag_exprs=["g_leak"],
    )
    base_1d = compile_symbolic_system(base_1d_spec)
    cal_rep = calibrate_and_audit_residual(
        brick=base_1d,
        observed_states=obs_v_only,
        dt=dt,
        observed_dx_dt=obs_dv_only,
        noise_floor_std=1e-3,
        custom_bounds={"g_leak": (0.1, 0.1)},
    )
    assert cal_rep.residual_analysis.max_snr > 50.0

    mem_rep = detect_non_markovian_memory(obs_v_only, cal_rep.residual_analysis.residual_flow, dt=dt)
    assert mem_rep.is_non_markovian
    assert mem_rep.hysteresis_ratio > 0.65

    disc_rep = discover_and_compile_law(
        base_brick=base_1d,
        observed_states=obs_v_only,
        dt=dt,
        observed_dx_dt=obs_dv_only,
        calibration_report=cal_rep,
    )
    assert disc_rep.discovery_triggered
    assert disc_rep.latent_augmentation is not None
    assert isinstance(disc_rep.winning_brick, LatentAugmentedLawBrick)
    assert disc_rep.winning_brick.state_dim == 2
    assert disc_rep.latent_augmentation.trajectory_r2 > 0.96
    assert disc_rep.audit_certificate.passed_all
    assert disc_rep.archetype.archetype_name == "non_markovian_latent_adaptation_loop"


